"""
Урок 2.4 · Задача 4 — Конвертер валют (БЕЗ автоперевірки)

Програма питає суму в гривнях і курс долара, а виводить результат
з 2 знаками після коми, наприклад:

    Сума в грн: 5000
    Курс USD: 41.5
    5000.00 грн = 120.48 $

Тут є input(), тому автоперевірки немає: запусти й порівняй з прикладом сам.
Перевір і «погане» введення: що буде, якщо ввести літери? (Чому — дізнаєшся в модулі 6.)
"""

# ↓↓↓ ТВІЙ КОД НИЖЧЕ ↓↓↓

grivna = float(input("Напиши суму в гривнях: "))
dollar = float(input("Напиши курс долара: "))
convertation = grivna / dollar
print(f"{grivna:.2f} грн = {convertation:.2f} $")